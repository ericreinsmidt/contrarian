def draw(d, text, x, y, px, colour, gap=1):
    """Blit text at pixel scale px. Returns the advance width."""
    cx = x
    for ch in text:
        g = G.get(ch.upper(), G[' '])
        for ry, row in enumerate(g):
            for rx, c in enumerate(row):
                if c == '1':
                    d.rectangle([cx+rx*px, y+ry*px, cx+(rx+1)*px-1, y+(ry+1)*px-1],
                                fill=colour)
        cx += (5+gap)*px
    return cx - x

def width(text, px, gap=1):
    return len(text)*(5+gap)*px - gap*px

def draw_glyph(d, rows, x, y, px, colour):
    for ry, row in enumerate(rows):
        for rx, c in enumerate(row):
            if c == '1':
                d.rectangle([x+rx*px, y+ry*px, x+(rx+1)*px-1, y+(ry+1)*px-1],
                            fill=colour)
